        //3. Polymorphism: The ability of different classes to be treated as instances of the same class through a common interface. It allows for methods to be used interchangeably, even if they belong to different classes.
        //4. Abstraction: The process of hiding the complex implementation details and showing only the necessary features of an object. It helps in reducing programming complexity and effort.
        
